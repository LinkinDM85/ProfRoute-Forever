--
-- БАЗА v1: рецепты и пороги сложности собраны по классическим гайдам и могут
-- отличаться на сервере Forever. База легко расширяется — просто добавьте
-- рецепт в нужный список, планировщик сам подхватит его при расчёте.
-- ============================================================================

